"""Certified exclusion of toroidal flux surfaces by lost cells on a cage (torux.nonstell, theorem CAGE), and
a certified upper bound on the toroidal flux of every surface (theorem FLUXBOUND, flux_bound).

Status: both are rigorous but, as implemented, not decisive on the data.  CAGE: a cell next
to a straight wire certifies at rho ~ d / 1000 (tests); covering the cage of a coil set needs 1e5..1e6
cells (B_phi / |B| ~ 1e-5..1e-2 near near-antisymmetric planes and in the far field, the second-derivative
bound ~15x the true |D^2 b|), so it was not run.  FLUXBOUND: computed for 65 sources; its Phi_max is
0.56..1e16 (median 49) times the largest actual half-plane int |B_phi| dA, i.e. no practical restriction
(near-coil cells are bounded by |B|, not B_phi; Lipschitz slack of the 3 % cells).  Ways forward: bound
B_phi of a near piece by |B_j| |t_j x e_phi| (toroidal bars), adaptive cells near the coils, the true
|D^2 b| from finite differences of the reference gradient of b in the tube bound, GPU throughput.

Lemma A (torux/barrier.py): R B_phi = x B_y - y B_x is harmonic in the vacuum region.  A toroidal flux
surface T (B_phi > 0 on T, or < 0 on T; solid torus V free of sources) therefore has B_phi of that
sign on all of V-bar, and every field line through V-bar stays in V-bar.  A point is LOST if its
field line reaches a point with B_phi < 0 and a point with B_phi > 0: lost points lie in no V-bar,
for either orientation.

CAGE.  C is a closed solid containing every coil in its interior: the solid cylinder
{R <= R_hi, Z_lo <= Z <= Z_hi} (complement simply connected), or, when every coil has toroidal winding
w_z = 0 (window / saddle / TF-type loops; no rings, no ToroidalField), the solid annulus
{R_lo <= R <= R_hi, ...} (H_1 of the complement is generated by a loop around the annulus' cross
section, which links each coil w_z = 0 times).  If V-bar missed C, every closed curve in V would have
zero linking number with every coil, so I_link = 0, contradicting AMP (torux.nonstell).  Hence V-bar
meets C.  If every point of the boundary dC is lost, V-bar (connected) lies in the interior of C, so
its section D_phi0 at any angle phi0 lies in the section S = C n {phi = phi0}.  If every point of S is
lost too, D_phi0 is empty: NO toroidal flux surface exists.  Coils with exact nfp-fold rotation
symmetry (verified by the loaders) let dC be certified on one period only (lost-ness is invariant).

Certified lost cells.  A cell (a patch of dC or S with centre c and radius rho) is lost if every
point z of it reaches B_phi < 0 and B_phi > 0.  The centre's line gamma is followed in arc length
along +B and -B (Dormand-Prince 5(4) with the variational equation M' = Db(gamma) M, b = B / |B|, on
the reference field torux.reference.fast64 with its gradient); for z with |z - c| <= rho,
w(s) = Phi_s(z) - gamma(s) satisfies w' = Db w + E, |E| <= K |w|^2 / 2, so (variation of constants,
bootstrap |w| <= R_t)

    |w(s)| <= r(s) = ||M(s)|| (rho + R_t^2 / 2 int_0^s ||M^-1|| K dt + E_int(s)),

where K bounds |D^2 b| <= |D^2 B| / |B| + 3 |DB|^2 / |B|^2 over the tube of radius R_t + h around
each step: |DB| and |B| from the reference value at the step ends and the bound on |D^2 B|; |D^2 B|
from the analytic Biot-Savart bound per straight piece of coil (length L, distance d from the
tube, current I): (mu0 |I| / 4 pi) 24 min(L / d^4, (pi / 2) / d^3) (the kernel r / |r|^3 has second
derivatives bounded by 24 / |r|^4; integral over an infinite line of 1 / |r|^4 = pi / (2 d^3));
Fourier curves and rings enter as fine polygons whose pieces are enlarged by their sagitta bound;
E_int carries the integrator's local error estimates (x 10) propagated by ||M^-1||; norms are
Frobenius (>= spectral).  The cell is certified when at some s (either direction, s = 0 included)
f = B_phi / |B| satisfies f + Lip r < 0, and at some s' f - Lip r > 0, with
Lip = 2 |DB| / |B| + 1 / R the Lipschitz bound of f on the ball of radius r (|DB|, |B| bounded on
the ball as above).  Failed cells are split in four down to a minimum size; the cells left
uncertified are the exact residual of the proof.
"""
