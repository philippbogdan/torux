# ============================================================================ bound data
def bound_pieces(source, n_poly=1024):
    """Straight pieces (a, b, w = mu0 |I| / 4 pi, L_arc, sag) covering every current filament: polyline
    segments exactly (sag 0); Fourier curves / rings as n_poly-gons with sag = a bound on the distance
    from the chord to the true arc (curvature bound kappa * chord^2 / 8 x 1.5) and arc length
    <= 1.02 x chord (checked: kappa * chord < 0.1)."""
    A, Bp, W, L, S = [], [], [], [], []
    has_tor = False
    for p in source.parts:
        if p.kind == "polyline":
            for i in range(p.n):
                x = p.loop(i); y = np.roll(x, -1, axis=0)
                c = np.linalg.norm(y - x, axis=1)
                A.append(x); Bp.append(y); W.append(np.full(len(x), MU0 / (4 * math.pi) * abs(p.current[i])))
                L.append(c); S.append(np.zeros(len(x)))
        elif p.kind == "segments":
            c = np.linalg.norm(p.b - p.a, axis=1)
            A.append(p.a); Bp.append(p.b); W.append(MU0 / (4 * math.pi) * np.abs(p.current)); L.append(c)
            S.append(np.zeros(len(c)))
        elif p.kind == "fourier":
            t = np.arange(n_poly) / n_poly
            x, dx = p.points(t)
            tf = np.arange(8 * n_poly) / (8 * n_poly)
            xf, dxf = p.points(tf)
            # second derivative by spectral differentiation of the fine samples
            for i in range(p.n):
                d2 = np.gradient(dxf[i], tf, axis=0)
                sp = np.linalg.norm(dxf[i], axis=1)
                kap = float(np.max(np.linalg.norm(np.cross(dxf[i], d2), axis=1) / sp ** 3)) * 1.2
                xi = x[i]; yi = np.roll(xi, -1, axis=0)
                c = np.linalg.norm(yi - xi, axis=1)
                assert float(np.max(kap * c)) < 0.1, "polygon too coarse for the bound"
                A.append(xi); Bp.append(yi); W.append(np.full(n_poly, MU0 / (4 * math.pi) * abs(p.current[i])))
                L.append(1.02 * c); S.append(1.5 * kap * c ** 2 / 8)
        elif p.kind == "rings":
            t = TWO_PI * np.arange(n_poly) / n_poly
            for i in range(p.n):
                xi = np.stack([p.R[i] * np.cos(t), p.R[i] * np.sin(t), np.full(n_poly, p.Z[i])], -1)
                yi = np.roll(xi, -1, axis=0)
                c = np.linalg.norm(yi - xi, axis=1)
                A.append(xi); Bp.append(yi); W.append(np.full(n_poly, MU0 / (4 * math.pi) * abs(p.current[i])))
                L.append(1.02 * c); S.append(np.full(n_poly, p.R[i] * (1 - math.cos(math.pi / n_poly)) * 1.01))
        elif p.kind == "toroidal":
            has_tor = True
        else:
            raise ValueError("bound_pieces: unsupported part %s" % p.kind)
    return (np.ascontiguousarray(np.concatenate(A)), np.ascontiguousarray(np.concatenate(Bp)),
            np.ascontiguousarray(np.concatenate(W)), np.ascontiguousarray(np.concatenate(L)),
            np.ascontiguousarray(np.concatenate(S))), has_tor


@njit(cache=True)
def _seg_dist(x0, x1, x2, a, b):
    ux = b[0] - a[0]; uy = b[1] - a[1]; uz = b[2] - a[2]
    vx = x0 - a[0]; vy = x1 - a[1]; vz = x2 - a[2]
    uu = ux * ux + uy * uy + uz * uz
    t = 0.0 if uu == 0.0 else (vx * ux + vy * uy + vz * uz) / uu
    if t < 0.0:
        t = 0.0
    elif t > 1.0:
        t = 1.0
    dx = vx - t * ux; dy = vy - t * uy; dz = vz - t * uz
    return math.sqrt(dx * dx + dy * dy + dz * dz)


@njit(cache=True)
def dkb_bound(Q, x0, x1, x2, rad, k):
    """Upper bound on |D^k B| (k = 2, 3, 4; symmetric-tensor norm) over the ball of radius rad
    around x: sum over pieces of (mu0 |I| / 4 pi) (k+1)! min(L / d^(k+2), c_k / d^(k+1)) with
    |D^k (r / |r|^3)| = |D^(k+1) (1 / |r|)| <= (k+1)! / |r|^(k+2) (Legendre bound) and c_k the
    integral over an infinite line of (1 + t^2)^(-(k+2)/2): pi/2, 4/3, 3 pi / 8."""
    a, b, w, L, S = Q
    if k == 2:
        fac = 6.0; ck = 0.5 * math.pi
    elif k == 3:
        fac = 24.0; ck = 4.0 / 3.0
    else:
        fac = 120.0; ck = 3.0 * math.pi / 8.0
    tot = 0.0
    for j in range(w.shape[0]):
        d = _seg_dist(x0, x1, x2, a[j], b[j]) - rad - S[j]
        if d <= 0.0:
            return np.inf
        dk1 = d ** (k + 1)
        v1 = L[j] / (dk1 * d)
        v2 = ck / dk1
        tot += w[j] * fac * (v1 if v1 < v2 else v2)
    return tot


@njit(cache=True)
def d2b_bound(Q, x0, x1, x2, rad):
    return dkb_bound(Q, x0, x1, x2, rad, 2)


@njit(cache=True)
def min_dist(Q, x0, x1, x2):
    a, b, w, L, S = Q
    m = np.inf
    for j in range(w.shape[0]):
        d = _seg_dist(x0, x1, x2, a[j], b[j]) - S[j]
        if d < m:
            m = d
    return m


# ============================================================================ field + variational rhs
@njit(cache=True, error_model="numpy")
def _field(P, x0, x1, x2, out):
    eval_point(P, x0, x1, x2, True, out)


@njit(cache=True, error_model="numpy")
def _rhs(P, y, sig, dy, buf):
    """dy/ds for y = (x, M (row-major 3x3)): x' = sig b, M' = sig Db M.  Returns |B| (0 on failure)."""
    _field(P, y[0], y[1], y[2], buf)
    Bx = buf[0]; By = buf[1]; Bz = buf[2]
    nb = math.sqrt(Bx * Bx + By * By + Bz * Bz)
    if not (nb > 0.0) or nb != nb:
        return 0.0
    bx = Bx / nb; by = By / nb; bz = Bz / nb
    dy[0] = sig * bx; dy[1] = sig * by; dy[2] = sig * bz
    # Db_ij = (DB_ij - b_i sum_k b_k DB_kj) / |B|, DB_ij = buf[6 + 3 i + j] = dB_i / dx_j
    Db = np.empty(9)
    for j in range(3):
        c = bx * buf[6 + j] + by * buf[9 + j] + bz * buf[12 + j]
        Db[j] = (buf[6 + j] - bx * c) / nb
        Db[3 + j] = (buf[9 + j] - by * c) / nb
        Db[6 + j] = (buf[12 + j] - bz * c) / nb
    for i in range(3):
        for j in range(3):
            s = 0.0
            for k in range(3):
                s += Db[3 * i + k] * y[3 + 3 * k + j]
            dy[3 + 3 * i + j] = sig * s
    return nb


@njit(cache=True)
def _frob(M):
    s = 0.0
    for k in range(9):
        s += M[k] * M[k]
    return math.sqrt(s)


@njit(cache=True)
def _frob_inv(M):
    a, b, c, d, e, f, g, h, i = M[0], M[1], M[2], M[3], M[4], M[5], M[6], M[7], M[8]
    A = e * i - f * h; B_ = -(d * i - f * g); C = d * h - e * g
    D = -(b * i - c * h); E = a * i - c * g; F = -(a * h - b * g)
    G = b * f - c * e; H = -(a * f - c * d); I_ = a * e - b * d
    det = a * A + b * B_ + c * C
    if det == 0.0:
        return np.inf
    return math.sqrt(A * A + B_ * B_ + C * C + D * D + E * E + F * F + G * G + H * H + I_ * I_) / abs(det)


@njit(cache=True, error_model="numpy")
def _pointdata(P, x0, x1, x2, buf):
    """|B|, |DB|_F, f = B_phi / |B|, R at x."""
    _field(P, x0, x1, x2, buf)
    nb = math.sqrt(buf[0] ** 2 + buf[1] ** 2 + buf[2] ** 2)
    nd = 0.0
    for k in range(6, 15):
        nd += buf[k] * buf[k]
    R = math.sqrt(x0 * x0 + x1 * x1)
    f = ((-x1 * buf[0] + x0 * buf[1]) / R) / nb if (nb > 0 and R > 0) else 0.0
    return nb, math.sqrt(nd), f, R


@njit(cache=True, error_model="numpy")
def d2b_sharp(P, Q, x0, x1, x2, rad, ndb, buf):
    """Bound on |D^2 B| over the ball of radius rad around x: |FD of the reference gradient| (Frobenius
    of the 27 differences) + its error bound (delta^2 / 6 |D^4 B| + rounding 4e-14 |DB| / delta) +
    rad x the crude bound on |D^3 B| over the ball."""
    dm = min_dist(Q, x0, x1, x2)
    if not (dm > 0.0):
        return np.inf
    if rad >= dm:
        return np.inf
    de = 1e-3 * dm
    xp = np.array([x0, x1, x2])
    tot = 0.0
    for kk in range(3):
        xp[kk] += de
        eval_point(P, xp[0], xp[1], xp[2], True, buf)
        g1 = buf[6:15].copy()
        xp[kk] -= 2 * de
        eval_point(P, xp[0], xp[1], xp[2], True, buf)
        xp[kk] += de
        for q in range(9):
            v = (g1[q] - buf[6 + q]) / (2 * de)
            tot += v * v
    d4 = dkb_bound(Q, x0, x1, x2, de, 4)
    d3 = dkb_bound(Q, x0, x1, x2, rad, 3)
    if not (d4 < np.inf and d3 < np.inf):
        return np.inf
    return math.sqrt(tot) + de * de / 6.0 * d4 * 3.0 + 4e-14 * ndb / de + rad * d3


@njit(cache=True, error_model="numpy")
def _test_end(P, Q, x0, x1, x2, r, nb, nd, f, R):
    """(neg_ok, pos_ok) for the ball of radius r around x: f + Lip r < 0, f - Lip r > 0."""
    if r <= 0.0:
        return f < 0.0, f > 0.0
    d2 = d2b_sharp(P, Q, x0, x1, x2, r, nd, np.empty(15))
    if not (d2 < np.inf):
        return False, False
    DBb = nd + r * d2
    Bb = nb - r * DBb
    Rb = R - r
    if Bb <= 0.0 or Rb <= 0.0:
        return False, False
    lip = 2.0 * DBb / Bb + 1.0 / Rb
    return f + lip * r < 0.0, f - lip * r > 0.0


@njit(cache=True, error_model="numpy")
def certify_one(P, Q, c0, c1, c2, rho, Rfac, smax, tol, hmax, nmax, res, diag):
    """Certify that every point within rho of c reaches B_phi < 0 and B_phi > 0.
    res = [ok, s_neg, s_pos, r_neg, r_pos, steps, fail_code]; fail codes: 0 ok, 1 tube bound blew up,
    2 smax reached, 3 field bound failure (tube touches a coil or |B| lower bound <= 0), 4 step limit.
    The tube radius R_n of step n is chosen before the step as Rfac x the current bound (at least
    Rfac x rho) and checked after it (r_{n+1} <= R_n), so |w| <= R holds wherever K was evaluated.
    diag (m, 7): per accepted step s, |M|, J, K, r, f, R_tube (first m steps of the + direction)."""
    buf = np.empty(15)
    nb, nd, f, R = _pointdata(P, c0, c1, c2, buf)
    r0 = math.sqrt(3.0) * rho
    negok, posok = _test_end(P, Q, c0, c1, c2, r0, nb, nd, f, R)
    s_neg = 0.0 if negok else -1.0
    s_pos = 0.0 if posok else -1.0
    r_neg = r0; r_pos = r0
    code = 0
    steps = 0
    nd_diag = diag.shape[0]
    idiag = 0
    if negok and posok:
        res[0] = 1.0; res[1] = 0.0; res[2] = 0.0; res[3] = r0; res[4] = r0; res[5] = 0; res[6] = 0
        return
    for d in range(2):
        sig = 1.0 if d == 0 else -1.0
        y = np.zeros(12); y[0] = c0; y[1] = c1; y[2] = c2
        y[3] = 1.0; y[7] = 1.0; y[11] = 1.0
        k1 = np.empty(12); k2 = np.empty(12); k3 = np.empty(12); k4 = np.empty(12)
        k5 = np.empty(12); k6 = np.empty(12); k7 = np.empty(12); t = np.empty(12); yn = np.empty(12)
        if _rhs(P, y, sig, k1, buf) == 0.0:
            code = 3
            break
        nb0 = nb; nd0 = nd
        h = min(hmax, 0.25 * rho + 1e-3 * hmax)
        s = 0.0; G = 0.0; Eint = 0.0
        rcur = r0
        minv0 = _frob_inv(y[3:12])
        dcode = 2
        for it in range(nmax):
            steps += 1
            for q in range(12):
                t[q] = y[q] + h * (0.2 * k1[q])
            ok2 = _rhs(P, t, sig, k2, buf)
            for q in range(12):
                t[q] = y[q] + h * (3.0 / 40 * k1[q] + 9.0 / 40 * k2[q])
            ok3 = _rhs(P, t, sig, k3, buf)
            for q in range(12):
                t[q] = y[q] + h * (44.0 / 45 * k1[q] - 56.0 / 15 * k2[q] + 32.0 / 9 * k3[q])
            ok4 = _rhs(P, t, sig, k4, buf)
            for q in range(12):
                t[q] = y[q] + h * (19372.0 / 6561 * k1[q] - 25360.0 / 2187 * k2[q] + 64448.0 / 6561 * k3[q]
                                   - 212.0 / 729 * k4[q])
            ok5 = _rhs(P, t, sig, k5, buf)
            for q in range(12):
                t[q] = y[q] + h * (9017.0 / 3168 * k1[q] - 355.0 / 33 * k2[q] + 46732.0 / 5247 * k3[q]
                                   + 49.0 / 176 * k4[q] - 5103.0 / 18656 * k5[q])
            ok6 = _rhs(P, t, sig, k6, buf)
            for q in range(12):
                yn[q] = y[q] + h * (35.0 / 384 * k1[q] + 500.0 / 1113 * k3[q] + 125.0 / 192 * k4[q]
                                    - 2187.0 / 6784 * k5[q] + 11.0 / 84 * k6[q])
            ok7 = _rhs(P, yn, sig, k7, buf)
            if ok2 == 0.0 or ok3 == 0.0 or ok4 == 0.0 or ok5 == 0.0 or ok6 == 0.0 or ok7 == 0.0:
                dcode = 3
                break
            err = 0.0
            for q in range(3):
                e = h * (71.0 / 57600 * k1[q] - 71.0 / 16695 * k3[q] + 71.0 / 1920 * k4[q]
                         - 17253.0 / 339200 * k5[q] + 22.0 / 525 * k6[q] - 1.0 / 40 * k7[q])
                if abs(e) > err:
                    err = abs(e)
            if err > tol and h > 1e-9 * hmax:
                h = h * max(0.2, 0.9 * (tol / err) ** 0.2)
                continue
            nb1, nd1, f1, R1 = _pointdata(P, yn[0], yn[1], yn[2], buf)
            minv1 = _frob_inv(yn[3:12])
            mnorm = _frob(yn[3:12])
            # tube radius for this step (bootstrap), enlarged until consistent
            Rt = Rfac * max(rcur, rho)
            okstep = False
            for attempt in range(4):
                rad = Rt + h
                d2 = d2b_sharp(P, Q, yn[0], yn[1], yn[2], rad, max(nd0, nd1), buf)
                if not (d2 < np.inf):
                    break
                DBmax = max(nd0, nd1) + rad * d2
                Bmin = min(nb0, nb1) - rad * DBmax
                if Bmin <= 0.0:
                    break
                K = d2 / Bmin + 3.0 * DBmax * DBmax / (Bmin * Bmin)
                Gn = G + h * 1.05 * max(minv0, minv1) * 0.5 * K * Rt * Rt
                En = Eint + 10.0 * err * minv1
                rn = mnorm * (rho + Gn + En)
                if rn <= Rt:
                    okstep = True
                    break
                Rt = 2.0 * rn
            if not okstep:
                dcode = 1 if (d2 < np.inf and Bmin > 0.0) else 3
                if res.shape[0] >= 12:
                    res[7] = d2; res[8] = Bmin; res[9] = Rt; res[10] = s; res[11] = mnorm
                break
            G = Gn; Eint = En; rcur = rn
            s += h
            for q in range(12):
                y[q] = yn[q]
                k1[q] = k7[q]
            minv0 = minv1; nb0 = nb1; nd0 = nd1
            if d == 0 and idiag < nd_diag:
                diag[idiag, 0] = s; diag[idiag, 1] = mnorm; diag[idiag, 2] = G; diag[idiag, 3] = K
                diag[idiag, 4] = rcur; diag[idiag, 5] = f1; diag[idiag, 6] = Rt
                idiag += 1
            negn, posn = _test_end(P, Q, y[0], y[1], y[2], rcur, nb1, nd1, f1, R1)
            if negn and not negok:
                negok = True; s_neg = sig * s; r_neg = rcur
            if posn and not posok:
                posok = True; s_pos = sig * s; r_pos = rcur
            if negok and posok:
                break
            if s > smax:
                dcode = 2
                break
            fac = 0.9 * (tol / max(err, 1e-300)) ** 0.2
            h = min(hmax, h * min(4.0, max(0.2, fac)))
        else:
            dcode = 4
        if negok and posok:
            break
        if code == 0 or dcode == 3:
            code = dcode
    res[0] = 1.0 if (negok and posok) else 0.0
    res[1] = s_neg; res[2] = s_pos; res[3] = r_neg; res[4] = r_pos; res[5] = steps
    res[6] = 0.0 if (negok and posok) else float(code if code else 2)


@njit(parallel=True, cache=True, error_model="numpy")
def certify_many(P, Q, C, rho, Rfac, smax, tol, hmax, nmax):
    n = C.shape[0]
    out = np.zeros((n, 7))
    for i in prange(n):
        r = np.zeros(7)
        certify_one(P, Q, C[i, 0], C[i, 1], C[i, 2], rho[i], Rfac, smax, tol, hmax, nmax, r, np.zeros((0, 7)))
        for k in range(7):
            out[i, k] = r[k]
    return out


# ============================================================================ cage surfaces
def _surf_point(surf, u, v, geo):
    """3D point of surface surf at parameters (u, v)."""
    if surf == "sec":                     # (R, Z) at phi0
        ph = geo["phi0"]
        return np.stack([u * np.cos(ph), u * np.sin(ph), v], -1)
    if surf in ("outer", "inner"):        # (phi, Z) at R = R_hi / R_lo
        R = geo["R_hi"] if surf == "outer" else geo["R_lo"]
        return np.stack([R * np.cos(u), R * np.sin(u), v], -1)
    if surf in ("top", "bot"):            # (R, phi) at Z = Z_hi / Z_lo
        Z = geo["Z_hi"] if surf == "top" else geo["Z_lo"]
        return np.stack([u * np.cos(v), u * np.sin(v), np.full(np.shape(u), Z)], -1)
    raise KeyError(surf)


def _cell_geom(surf, u0, u1, v0, v1, geo):
    uu, vv = np.meshgrid(np.linspace(u0, u1, 5), np.linspace(v0, v1, 5), indexing="ij")
    X = _surf_point(surf, uu.ravel(), vv.ravel(), geo)
    c = _surf_point(surf, np.array([0.5 * (u0 + u1)]), np.array([0.5 * (v0 + v1)]), geo)[0]
    rho = float(np.max(np.linalg.norm(X - c, axis=1))) * 1.05     # 5x5 samples + 5 % for curvature
    return c, rho


def cage_geometry(source, curves, margin=0.15, margin_in=None):
    """Cage dimensions, the section angle phi0 farthest from every coil, the symmetry period."""
    from .nonstell import toroidal_winding
    P = np.concatenate([c["pts"] for c in curves])
    R = np.hypot(P[:, 0], P[:, 1]); Z = P[:, 2]
    L = max(R.max(), Z.max() - Z.min())
    wz_all_zero = all(toroidal_winding(c["pts"]) == 0 for c in curves) and \
        not any(p.kind in ("rings", "toroidal", "axipoly") for p in source.parts)
    R_lo = R.min() - (margin if margin_in is None else margin_in) * L
    annular = wz_all_zero and R_lo > 0.05 * L
    geo = dict(R_hi=float(R.max() + margin * L), R_lo=float(R_lo) if annular else 0.0,
               Z_lo=float(Z.min() - margin * L), Z_hi=float(Z.max() + margin * L), L=float(L),
               annular=bool(annular))
    # section angle: maximise the distance from the half plane to the coil points
    ph = np.arctan2(P[:, 1], P[:, 0])
    best, bd = 0.0, -1.0
    for p0 in np.linspace(0, TWO_PI, 1440, endpoint=False):
        d = np.angle(np.exp(1j * (ph - p0)))
        dist = np.where(np.abs(d) <= 0.5 * np.pi, R * np.abs(np.sin(d)), R)
        m = float(dist.min())
        if m > bd:
            best, bd = float(p0), m
    geo["phi0"] = best
    geo["section_coil_distance"] = bd
    nfp = int(source.nfp) if source.nfp and source.nfp > 1 else 1
    geo["nfp"] = nfp
    return geo


def cage_cells(geo, h0):
    """Initial cells (surf, u0, u1, v0, v1) of size about h0 covering the cage boundary (one symmetry
    period) and the section."""
    cells = []
    R_lo, R_hi, Z_lo, Z_hi, nfp = geo["R_lo"], geo["R_hi"], geo["Z_lo"], geo["Z_hi"], geo["nfp"]
    per = TWO_PI / nfp

    def grid(surf, ua, ub, va, vb, hu, hv):
        nu = max(1, int(math.ceil((ub - ua) / hu))); nv = max(1, int(math.ceil((vb - va) / hv)))
        us = np.linspace(ua, ub, nu + 1); vs = np.linspace(va, vb, nv + 1)
        for i in range(nu):
            for j in range(nv):
                cells.append((surf, us[i], us[i + 1], vs[j], vs[j + 1]))
    grid("sec", R_lo, R_hi, Z_lo, Z_hi, h0, h0)
    grid("outer", geo["phi0"], geo["phi0"] + per, Z_lo, Z_hi, h0 / R_hi, h0)
    if geo["annular"]:
        grid("inner", geo["phi0"], geo["phi0"] + per, Z_lo, Z_hi, h0 / R_lo, h0)
    for surf in ("top", "bot"):
        # rings of cells in R; angular size h0 / R (outer radius of the ring)
        nR = max(1, int(math.ceil((R_hi - R_lo) / h0)))
        Rs = np.linspace(R_lo, R_hi, nR + 1)
        for i in range(nR):
            hv = h0 / max(Rs[i + 1], 1e-9)
            nv = max(1, int(math.ceil(per / hv)))
            vs = np.linspace(geo["phi0"], geo["phi0"] + per, nv + 1)
            for j in range(nv):
                cells.append((surf, Rs[i], Rs[i + 1], vs[j], vs[j + 1]))
    return cells


def certify_cage(source, margin=0.15, h0=None, min_size=None, max_cells=200000, smax=None, tol=None,
                 Rfac=1.5, budget_s=None, verbose=False):
    """Run the CAGE certification.  Returns a record: geometry, counts, residual cells, timing."""
    from .nonstell import closed_curves
    t0 = time.time()
    curves = closed_curves(source)
    Q, has_tor = bound_pieces(source)
    rec = dict(theorem="CAGE")
    if has_tor:
        rec.update(applicable=False, reason="ToroidalField part (z-axis current) links loops outside any cage")
        return rec
    geo = cage_geometry(source, curves, margin)
    rec["geometry"] = geo
    L = geo["L"]
    h0 = h0 or 0.08 * L
    min_size = min_size or 2e-4 * L
    smax = smax or 6.0 * L
    tol = tol or 1e-11 * L
    F = fast64.Field(source)
    queue = cage_cells(geo, h0)
    n_cert = 0; n_tried = 0; residual = []; codes = {}
    smax_used = 0.0
    level = 0
    while queue:
        if n_tried > max_cells or (budget_s and time.time() - t0 > budget_s):
            residual += [dict(surf=c[0], u=[c[1], c[2]], v=[c[3], c[4]], reason="budget") for c in queue]
            break
        geoms = [_cell_geom(c[0], c[1], c[2], c[3], c[4], geo) for c in queue]
        C = np.array([g[0] for g in geoms]); rho = np.array([g[1] for g in geoms])
        out = certify_many(F.packed, Q, C, rho, Rfac, smax, tol, 0.05 * L, 200000)
        n_tried += len(queue)
        nxt = []
        for c, (cc, rr), o in zip(queue, geoms, out):
            if o[0] == 1.0:
                n_cert += 1
                smax_used = max(smax_used, abs(o[1]), abs(o[2]))
                continue
            codes[int(o[6])] = codes.get(int(o[6]), 0) + 1
            if rr < min_size:
                dcoil = float(min_dist(Q, cc[0], cc[1], cc[2]))
                residual.append(dict(surf=c[0], u=[float(c[1]), float(c[2])], v=[float(c[3]), float(c[4])],
                                     centre=[float(v) for v in cc], rho=float(rr), code=int(o[6]),
                                     dist_to_coil=dcoil))
                continue
            um, vm = 0.5 * (c[1] + c[2]), 0.5 * (c[3] + c[4])
            nxt += [(c[0], c[1], um, c[3], vm), (c[0], um, c[2], c[3], vm),
                    (c[0], c[1], um, vm, c[4]), (c[0], um, c[2], vm, c[4])]
        if verbose:
            print(f"level {level}: {len(queue)} cells, certified so far {n_cert}, next {len(nxt)}, "
                  f"residual {len(residual)}, {time.time() - t0:.0f}s", flush=True)
        queue = nxt
        level += 1
    rec.update(applicable=True, n_cells_certified=n_cert, n_cells_tried=n_tried, n_residual=len(residual),
               residual=residual[:200], fail_codes=codes, max_arclength=float(smax_used), h0=h0,
               min_size=min_size, Rfac=Rfac, tol=tol, smax=smax, proved=len(residual) == 0,
               seconds=time.time() - t0)
    if residual:
        rec["residual_max_dist_to_coil"] = float(max(r.get("dist_to_coil", np.inf) for r in residual))
    return rec


