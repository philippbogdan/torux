@njit(cache=True, error_model="numpy")
def _bsup_crude(Q, x0, x1, x2, rad):
    """Upper bound on |B| over the ball (sum over pieces of (mu0 |I| / 4 pi) min(L / d^2, 2 / d))."""
    a, b, w, L, S = Q
    tot = 0.0
    for j in range(w.shape[0]):
        d = _seg_dist(x0, x1, x2, a[j], b[j]) - rad - S[j]
        if d <= 0.0:
            return np.inf
        v1 = L[j] / (d * d); v2 = 2.0 / d
        tot += w[j] * (v1 if v1 < v2 else v2)
    return tot


@njit(parallel=True, cache=True, error_model="numpy")
def halfplane_cells(P, Q, phi, R0, Z0, h, nR, nZ):
    """Cell bounds on the half plane phi: out[i, j] = [Bphi(c), U+, U-, sgn] with U+- upper bounds on
    int_cell max(+-B_phi, 0) dA and sgn = -1 (B_phi < 0 certified on the cell), +1 (> 0 certified), 0.
    Bounds: B_phi(c) +- rho (|DB| + rho |D2B| + (|B| + rho (|DB| + rho |D2B|)) / (R - rho)) with |D2B|
    from d2b_sharp; cells whose ball touches a coil piece get the crude sup of |B| (or infinity)."""
    out = np.zeros((nR, nZ, 4))
    c = math.cos(phi); s = math.sin(phi)
    rho = h / math.sqrt(2.0)
    area = h * h
    for i in prange(nR):
        buf = np.empty(15)
        for j in range(nZ):
            R = R0 + (i + 0.5) * h; Z = Z0 + (j + 0.5) * h
            x0 = R * c; x1 = R * s; x2 = Z
            eval_point(P, x0, x1, x2, True, buf)
            Bx = buf[0]; By = buf[1]
            bphi = -Bx * s + By * c
            nb = math.sqrt(buf[0] ** 2 + buf[1] ** 2 + buf[2] ** 2)
            nd = 0.0
            for k in range(6, 15):
                nd += buf[k] * buf[k]
            nd = math.sqrt(nd)
            d2 = d2b_sharp(P, Q, x0, x1, x2, rho, nd, np.empty(15))
            if d2 < np.inf and R - rho > 0.0:
                DBm = nd + rho * d2
                Bm = nb + rho * DBm
                lip = DBm + Bm / (R - rho)
                up = bphi + rho * lip
                lo = bphi - rho * lip
                out[i, j, 0] = bphi
                out[i, j, 1] = area * (up if up > 0.0 else 0.0)
                out[i, j, 2] = area * (-lo if lo < 0.0 else 0.0)
                out[i, j, 3] = -1.0 if up < 0.0 else (1.0 if lo > 0.0 else 0.0)
            else:
                out[i, j, 0] = bphi
                v = _near_cell_bound(Q, x0, x1, x2, rho, c, s, area)
                out[i, j, 1] = v
                out[i, j, 2] = v
                out[i, j, 3] = 0.0
    return out


@njit(cache=True, error_model="numpy")
def _near_cell_bound(Q, x0, x1, x2, rho, c, s, area):
    """Upper bound on int_cell |B| dA for a cell (square of half diagonal rho, centre x, in the plane
    with normal n = (-s, c, 0)) whose ball meets coil pieces: far pieces by area x sup |B|; a near piece
    crossing the plane at q with angle theta has |B_j(x)| <= (mu0 |I| / 4 pi) 2 / d(x),
    d(x) >= |x - q| sin(theta), so its integral over the cell (inside the disc of radius 2 rho about q)
    is <= (mu0 |I| / 4 pi) (2 / sin theta) 2 pi (2 rho); near pieces not crossing the plane, or with
    sin(theta) < 0.1, give infinity."""
    a, b, w, L, S = Q
    tot = 0.0
    for j in range(w.shape[0]):
        d = _seg_dist(x0, x1, x2, a[j], b[j]) - rho - S[j]
        if d > 0.0:
            v1 = L[j] / (d * d); v2 = 2.0 / d
            tot += area * w[j] * (v1 if v1 < v2 else v2)
            continue
        # near piece: crossing of the plane (signed distances of the end points to the plane)
        da = -a[j, 0] * s + a[j, 1] * c
        db = -b[j, 0] * s + b[j, 1] * c
        if S[j] > 0.25 * rho:
            return np.inf
        if da * db > 0.0:
            # piece on one side at distance >= hh from the plane: d(x) >= sqrt(y^2 + hh^2) with y the
            # in-plane distance to the projected line; over a square of side 2 rho (any orientation, inside
            # a strip of width 4 rho across the line): int dA / d <= 4 rho * 2 asinh(2 rho / hh)
            hh = min(abs(da), abs(db)) - S[j]
            if hh <= 0.0:
                return np.inf
            tot += w[j] * 2.0 * 4.0 * rho * 2.0 * math.asinh(2.0 * rho / hh)
            continue
        ux = b[j, 0] - a[j, 0]; uy = b[j, 1] - a[j, 1]; uz = b[j, 2] - a[j, 2]
        lu = math.sqrt(ux * ux + uy * uy + uz * uz)
        sint = abs(-ux * s + uy * c) / lu if lu > 0 else 0.0
        if sint < 0.1:
            return np.inf
        tot += w[j] * (2.0 / sint) * 2.0 * math.pi * (2.0 * rho)
    return tot


def multipole_data(curves, c0):
    """Total dipole moment m = sum I (1/2) loop integral of (y - c0) x dl, and the remainder constant:
    |B - B_dip|(x) <= C / (|x - c0| - a)^4 with C = sum (mu0 |I| / 4 pi) 3 P a_k^2, a = max a_k
    (Taylor remainder of K(x - y) = (x - y) / |x - y|^3 around y = c0, |D^2 K| <= 6 / |u|^4)."""
    m = np.zeros(3); C = 0.0; amax = 0.0
    for cv in curves:
        x = cv["pts"]; y = np.roll(x, -1, axis=0)
        dl = y - x
        mid = 0.5 * (x + y) - c0
        m += cv["I"] * 0.5 * np.cross(mid, dl).sum(0)
        ak = float(np.max(np.linalg.norm(x - c0, axis=1)))
        Pk = float(np.linalg.norm(dl, axis=1).sum())
        C += MU0 / (4 * math.pi) * abs(cv["I"]) * 3.0 * Pk * ak * ak
        amax = max(amax, ak)
    return m, C, amax


def tail_bound(md, c0, phi, box, sign):
    """Upper bound on int max(sign B_phi, 0) dA over the half plane phi outside the box: with c0 on the z
    axis, B_dip has B_phi = -(mu0 / 4 pi) m.e_phi / |u|^3 on the half plane (u in the meridional plane);
    if -sign m.e_phi <= 0 the dipole adds nothing to the positive part, else (mu0/4pi) |m.e_phi| pi / D;
    the remainder adds C pi [1 / (2 (D - a)^2) + a / (3 (D - a)^3)], D = distance from c0 to the outside
    of the box within the half plane (D > a required)."""
    m, C, a = md
    R0, R1, Z0, Z1 = box
    zc = c0[2]
    D = min(R1, zc - Z0, Z1 - zc)
    if not (D > a):
        return np.inf
    ephi = np.array([-math.sin(phi), math.cos(phi), 0.0])
    dip = -MU0 / (4 * math.pi) * float(m @ ephi)            # B_phi,dip * |u|^3
    tot = 0.0
    if sign * dip > 0:
        tot += abs(dip) * math.pi / D
    tot += C * math.pi * (1.0 / (2 * (D - a) ** 2) + a / (3 * (D - a) ** 3))
    return tot


@njit(cache=True, error_model="numpy")
def _cell_bound(P, Q, x0, x1, x2, R, rho, area, c, s, buf):
    """(B_phi(c), U+, U-, sign) for a cell of the half plane (centre x, half diagonal rho, area)."""
    eval_point(P, x0, x1, x2, True, buf)
    bphi = -buf[0] * s + buf[1] * c
    nb = math.sqrt(buf[0] ** 2 + buf[1] ** 2 + buf[2] ** 2)
    nd = 0.0
    for k in range(6, 15):
        nd += buf[k] * buf[k]
    nd = math.sqrt(nd)
    dm = min_dist(Q, x0, x1, x2)
    if dm > 2.0 * rho and R - rho > 0.0:
        if dm > 20.0 * rho:
            d2 = dkb_bound(Q, x0, x1, x2, rho, 2)
        else:
            d2 = d2b_sharp(P, Q, x0, x1, x2, rho, nd, np.empty(15))
        if d2 < np.inf:
            DBm = nd + rho * d2
            Bm = nb + rho * DBm
            lip = DBm + Bm / (R - rho)
            up = bphi + rho * lip
            lo = bphi - rho * lip
            sg = -1.0 if up < 0.0 else (1.0 if lo > 0.0 else 0.0)
            return bphi, area * (up if up > 0.0 else 0.0), area * (-lo if lo < 0.0 else 0.0), sg
    v = _near_cell_bound(Q, x0, x1, x2, rho, c, s, area)
    return bphi, v, v, 0.0


@njit(parallel=True, cache=True, error_model="numpy")
def polar_cells(P, Q, phi, zc, lnr0, dlnr, nr, th0, dth, nth):
    """Cells of the half plane phi in polar coordinates about (R, Z) = (0, zc): rho in
    [exp(lnr0 + i dlnr), exp(lnr0 + (i+1) dlnr)], theta (from +R towards +Z) in [th0 + j dth, ...].
    out[i, j] = [B_phi(c), U+, U-, sign]."""
    out = np.zeros((nr, nth, 4))
    c = math.cos(phi); s = math.sin(phi)
    for i in prange(nr):
        buf = np.empty(15)
        ra = math.exp(lnr0 + i * dlnr); rb = math.exp(lnr0 + (i + 1) * dlnr)
        for j in range(nth):
            ta = th0 + j * dth; tb = ta + dth
            rm = 0.5 * (ra + rb); tm = 0.5 * (ta + tb)
            R = rm * math.cos(tm); Z = zc + rm * math.sin(tm)
            area = 0.5 * (rb * rb - ra * ra) * dth
            # half diagonal: max distance from the centre to the 4 corners
            rho = 0.0
            for (rr, tt) in ((ra, ta), (ra, tb), (rb, ta), (rb, tb)):
                dx = rr * math.cos(tt) - R; dz = zc + rr * math.sin(tt) - Z
                d = math.sqrt(dx * dx + dz * dz)
                if d > rho:
                    rho = d
            rho *= 1.02
            b, up, um, sg = _cell_bound(P, Q, R * c, R * s, Z, R, rho, area, c, s, buf)
            out[i, j, 0] = b; out[i, j, 1] = up; out[i, j, 2] = um; out[i, j, 3] = sg
    return out


def flux_bound(source, n_angle=96, dln=None, rmin_rel=1e-3, rmax_rel=1e4, n_scan_phi=72, n_best=2, verbose=False):
    """FLUXBOUND: certified upper bound on |toroidal flux| of every toroidal flux surface.

    Lemma A: a surface with B_phi > 0 on it has B_phi > 0 on its whole solid torus (no source inside),
    so its section D_phi in any half plane H_phi lies in {B_phi > 0} and its flux is at most
    int_{H_phi} B_phi^+ dA; likewise B_phi^- for surfaces with B_phi < 0.  The integral is bounded from
    above on a polar grid about (R, Z) = (0, z_c) (log-spaced radii from rmin to rmax, n_angle angles):
    per cell area x max(0, B_phi(c) + rho Lip), Lip = |DB| + rho |D^2 B| + (|B| + ...) / (R - rho) with
    |D^2 B| from d2b_sharp (or the analytic piece bound far from the coils); cells whose ball meets a coil
    piece get the 1/d integral bound (_near_cell_bound); the half disc rho < rmin gets area x sup |B|
    (analytic); the region rho > rmax the dipole + multipole-remainder bound (tail_bound).  The bound
    holds for every phi; the smallest over the angles tried is kept, separately for each sign.
    Not applicable with a ToroidalField part."""
    from .nonstell import closed_curves
    t0 = time.time()
    curves = closed_curves(source)
    Q, has_tor = bound_pieces(source)
    if has_tor:
        return dict(theorem="FLUXBOUND", applicable=False, reason="ToroidalField part (1/R field)")
    F = fast64.Field(source)
    P = np.concatenate([c["pts"] for c in curves])
    Rc = np.hypot(P[:, 0], P[:, 1]); L = max(Rc.max(), np.ptp(P[:, 2]))
    zc = 0.5 * (P[:, 2].min() + P[:, 2].max())
    c0 = np.array([0.0, 0.0, zc])
    md = multipole_data(curves, c0)
    rmin, rmax = rmin_rel * L, rmax_rel * L
    nth = n_angle
    dth = math.pi / nth
    dln = dln or dth
    nr = int(math.ceil(math.log(rmax / rmin) / dln))
    dln = math.log(rmax / rmin) / nr
    # pre-scan of the half planes (coarse polar grid, values only) to pick the angles
    phis = np.linspace(0, TWO_PI, n_scan_phi, endpoint=False)
    rs = np.exp(np.linspace(math.log(0.05 * L), math.log(4 * L), 40)); ts = np.linspace(-0.5 * math.pi, 0.5 * math.pi, 41)[1:-1]
    RRp, TTp = np.meshgrid(rs, ts, indexing="ij")
    wgt = (RRp ** 2).ravel()
    sc_p, sc_m = [], []
    for ph in phis:
        Rq = (RRp * np.cos(TTp)).ravel(); Zq = (zc + RRp * np.sin(TTp)).ravel()
        X = np.stack([Rq * math.cos(ph), Rq * math.sin(ph), Zq], -1)
        B = F.evaluate(X, grad=False)["B"]
        bp = -B[:, 0] * math.sin(ph) + B[:, 1] * math.cos(ph)
        sc_p.append(float(np.sum(np.maximum(bp, 0) * wgt))); sc_m.append(float(np.sum(np.maximum(-bp, 0) * wgt)))
    cand = sorted(set(list(np.argsort(sc_p)[:n_best]) + list(np.argsort(sc_m)[:n_best])))
    best = {+1: (np.inf, None), -1: (np.inf, None)}
    per_phi = []
    for k in cand:
        ph = float(phis[k])
        out = polar_cells(F.packed, Q, ph, zc, math.log(rmin), dln, nr, -0.5 * math.pi, dth, nth)
        inner = 0.5 * math.pi * rmin ** 2 * float(_bsup_crude(Q, c0[0], c0[1], c0[2], rmin))
        rec = dict(phi=ph, n_cells=int(nr * nth), inner=inner)
        for sgn, col in ((+1, 1), (-1, 2)):
            tail = tail_bound(md, c0, ph, (0.0, rmax, zc - rmax, zc + rmax), sgn)
            body = float(np.sum(out[:, :, col]))
            bound = body + inner + tail
            rec["plus" if sgn > 0 else "minus"] = dict(bound=bound, body=body, tail=tail,
                                                      n_inf_cells=int(np.isinf(out[:, :, col]).sum()),
                                                      n_cert_opposite=int((out[:, :, 3] == -sgn).sum()))
            if bound < best[sgn][0]:
                best[sgn] = (bound, ph)
        rec["int_absBphi"] = float(np.sum(np.abs(out[:, :, 0]) * _polar_areas(rmin, dln, nr, dth, nth)[:, None]))
        per_phi.append(rec)
        if verbose:
            print(f"phi {ph:.4f}: + {rec['plus']['bound']:.3e}  - {rec['minus']['bound']:.3e}  "
                  f"(int |B_phi| {rec['int_absBphi']:.3e}, inner {inner:.1e}, tails {rec['plus']['tail']:.1e} "
                  f"{rec['minus']['tail']:.1e}, inf cells {rec['plus']['n_inf_cells']})  {time.time() - t0:.0f}s", flush=True)
    Phi = max(best[1][0], best[-1][0])
    ref = max(r["int_absBphi"] for r in per_phi)
    return dict(theorem="FLUXBOUND", applicable=True, Phi_max=float(Phi), Phi_plus=float(best[1][0]),
                phi_plus=best[1][1], Phi_minus=float(best[-1][0]), phi_minus=best[-1][1],
                dipole_moment=[float(v) for v in md[0]], remainder_C=float(md[1]), a=float(md[2]),
                grid=dict(rmin=rmin, rmax=rmax, n_r=nr, n_theta=nth), per_phi=per_phi,
                ref_int_absBphi=ref, ratio=float(Phi / max(ref, 1e-300)), seconds=time.time() - t0)


def _polar_areas(rmin, dln, nr, dth, nth):
    ra = rmin * np.exp(np.arange(nr) * dln); rb = ra * math.exp(dln)
    return 0.5 * (rb ** 2 - ra ** 2) * dth


def flux_scale(source, n_phi=36):
    """Reference scale for FLUXBOUND: the largest int |B_phi| dA over the half planes (coarse polar
    grid 0.02 L .. 8 L about (0, z_c), 48 x 40 nodes; an estimate, not a bound)."""
    from .nonstell import closed_curves
    curves = closed_curves(source)
    P = np.concatenate([c["pts"] for c in curves])
    Rc = np.hypot(P[:, 0], P[:, 1]); L = max(Rc.max(), np.ptp(P[:, 2]))
    zc = 0.5 * (P[:, 2].min() + P[:, 2].max())
    F = fast64.Field(source)
    lr = np.linspace(math.log(0.02 * L), math.log(8 * L), 49); rm = np.exp(0.5 * (lr[1:] + lr[:-1]))
    th = np.linspace(-0.5 * math.pi, 0.5 * math.pi, 41); tm = 0.5 * (th[1:] + th[:-1])
    RR, TT = np.meshgrid(rm, tm, indexing="ij")
    dA = (RR ** 2 * (lr[1] - lr[0]) * (th[1] - th[0])).ravel()
    best = 0.0
    for ph in np.linspace(0, TWO_PI, n_phi, endpoint=False):
        Rq = (RR * np.cos(TT)).ravel(); Zq = (zc + RR * np.sin(TT)).ravel()
        B = F.evaluate(np.stack([Rq * math.cos(ph), Rq * math.sin(ph), Zq], -1), grad=False)["B"]
        bp = -B[:, 0] * math.sin(ph) + B[:, 1] * math.cos(ph)
        best = max(best, float(np.sum(np.abs(bp) * dA)))
    return best
